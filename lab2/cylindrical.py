"""Bonus: cylindrical projection and stitching, separate from the HW interfaces.

Pixel coordinates are (x, y); arrays use [y, x]. Cylindrical coordinates (u, v)
are centered, measured in pixels, and use a cylinder of radius f. Input colors
are BGR, as returned by cv2.imread. The model assumes a level camera rotating
about its optical center, with one shared focal length in pixels.
"""

import cv2
import numpy as np


def cylindrical_points(points, image_shape, focal_length):
    """Map original (x, y) points to centered, unrolled cylinder coordinates."""
    f = float(focal_length)
    if not np.isfinite(f) or f <= 0:
        raise ValueError('focal_length must be positive and finite (in pixels)')
    h, w = image_shape[:2]
    points = np.asarray(points, dtype=np.float64).reshape(-1, 2)
    x = points[:, 0] - (w - 1) / 2
    y = points[:, 1] - (h - 1) / 2
    return np.column_stack((f * np.arctan2(x, f),
                            f * y / np.sqrt(x * x + f * f)))


def cylindrical_inverse_maps(u, v, image_shape, focal_length):
    """Return float32 source maps for cv2.remap; u/v may broadcast.

    u/v are centered LOCAL cylinder coordinates, after undoing the frame's
    global translation. Reject the back of the camera explicitly: tan(theta)
    is periodic, so checking source bounds alone would also sample behind it.
    """
    f = float(focal_length)
    if not np.isfinite(f) or f <= 0:
        raise ValueError('focal_length must be positive and finite (in pixels)')
    h, w = image_shape[:2]
    u, v = np.broadcast_arrays(np.asarray(u, dtype=np.float32),
                               np.asarray(v, dtype=np.float32))
    theta = u / f
    front = np.isfinite(theta) & np.isfinite(v) & (np.abs(theta) < np.pi / 2)
    safe_theta = np.where(front, theta, 0)
    map_x = (w - 1) / 2 + f * np.tan(safe_theta)
    map_y = (h - 1) / 2 + v / np.cos(safe_theta)
    # Outside this range even bilinear interpolation has zero coverage.
    valid = front & (map_x > -1) & (map_x < w) & (map_y > -1) & (map_y < h)
    return (np.where(valid, map_x, -1).astype(np.float32),
            np.where(valid, map_y, -1).astype(np.float32))


def _bounds(image_shape, focal_length, offset=(0, 0)):
    """Continuous bounding rectangle; vertical extrema occur at edge MIDPOINTS.

    Four projected corners alone would crop off the top/bottom central pixels.
    """
    h, w = image_shape[:2]
    cx, cy = (w - 1) / 2, (h - 1) / 2
    half_width = focal_length * np.arctan2(cx, focal_length)
    return (offset[0] - half_width, offset[1] - cy,
            offset[0] + half_width, offset[1] + cy)


def cylindrical_warp(image, focal_length):
    """Project one original image; return (float32 image, coverage, origin).

    coverage is a 2D float array in [0, 1], generated by remapping an all-ones
    source with the SAME maps and zero border. A genuinely black pixel still
    has coverage 1. origin is the cylinder (u, v) at output array index [0, 0].
    """
    # Validate f even for a single image.
    cylindrical_points([], image.shape, focal_length)
    left, top, right, bottom = _bounds(image.shape, focal_length)
    left, top = int(np.floor(left)), int(np.floor(top))
    right, bottom = int(np.ceil(right)), int(np.ceil(bottom))
    u, v = np.meshgrid(np.arange(left, right + 1, dtype=np.float32),
                       np.arange(top, bottom + 1, dtype=np.float32))
    map_x, map_y = cylindrical_inverse_maps(u, v, image.shape, focal_length)
    color = cv2.remap(image.astype(np.float32), map_x, map_y, cv2.INTER_LINEAR,
                      borderMode=cv2.BORDER_CONSTANT, borderValue=0)
    cover = cv2.remap(np.ones(image.shape[:2], np.float32), map_x, map_y,
                      cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT,
                      borderValue=0)
    divisor = cover[..., None] if image.ndim == 3 else cover
    # Restore straight colors: remap already multiplied edge colors by coverage.
    color = color / np.maximum(divisor, 1e-6)
    return color, cover, (left, top)


def ransac_translation(source, target, threshold=3.0, iterations=1000, seed=0):
    """Estimate target = source + shift; return (shift, final inlier mask).

    One correspondence proposes a translation. Refit using the consensus mean,
    then report inliers of the actual returned translation.
    """
    source = np.asarray(source, dtype=np.float64).reshape(-1, 2)
    target = np.asarray(target, dtype=np.float64).reshape(-1, 2)
    if source.shape != target.shape or not len(source):
        raise ValueError('Translation needs nonempty, corresponding point lists')
    if threshold <= 0 or iterations < 1:
        raise ValueError('threshold and iterations must be positive')
    displacements = target - source
    rng = np.random.default_rng(seed)
    candidates = rng.choice(len(source), size=min(iterations, len(source)),
                            replace=False)
    best_mask = np.zeros(len(source), dtype=bool)
    best_count, best_error = 0, np.inf
    for index in candidates:
        errors = np.linalg.norm(displacements - displacements[index], axis=1)
        mask = errors < threshold
        count = int(mask.sum())
        error = float(np.mean(errors[mask] ** 2))
        if count > best_count or (count == best_count and error < best_error):
            best_mask, best_count, best_error = mask, count, error
    shift = displacements[best_mask].mean(axis=0)
    for _ in range(5):
        mask = np.linalg.norm(displacements - shift, axis=1) < threshold
        if not mask.any():
            break
        updated = displacements[mask].mean(axis=0)
        if np.allclose(updated, shift, atol=1e-8, rtol=0):
            shift = updated
            break
        shift = updated
    inliers = np.linalg.norm(displacements - shift, axis=1) < threshold
    return shift, inliers


def _source_weights(shape, blend):
    h, w = shape[:2]
    if blend == 'average':
        return np.ones((h, w), np.float32)
    if blend != 'feather':
        raise ValueError("blend must be 'average' or 'feather'")
    # Distance to a zero border just OUTSIDE the source. Positive at edge pixels;
    # valid black source pixels receive the same weights as any other color.
    yy, xx = np.indices((h, w), dtype=np.float32)
    weights = np.minimum(np.minimum(xx + 1, w - xx),
                         np.minimum(yy + 1, h - yy))
    return weights / weights.max()


def estimate_cylindrical_focal_length(point_pairs, image_shape, threshold=3.0,
                                      seed=0):
    """Estimate f from a COMPLETE one-turn loop, including last/first matches.

    The signed sum of angular increments must be +/-2*pi. This is a geometric
    estimate under the level-yaw model, not general camera calibration. It is
    not valid for a partial sequence or multiple turns. Each pair maps the next
    camera into the previous camera; the final pair closes camera 0 into n-1.
    """
    from scipy.optimize import brentq

    point_pairs = list(point_pairs)

    def loop_angle_error(f):
        total = 0.0
        for source, target in point_pairs:
            src = cylindrical_points(source, image_shape, f)
            dst = cylindrical_points(target, image_shape, f)
            shift, _ = ransac_translation(src, dst, threshold=threshold, seed=seed)
            total += shift[0] / f
        return abs(total) - 2 * np.pi

    w = image_shape[1]
    low, high = 0.4 * w, 4.0 * w
    if loop_angle_error(low) * loop_angle_error(high) >= 0:
        raise ValueError('Cannot estimate f in [0.4w, 4w]; check matches and '
                         'whether this sequence contains exactly one turn')
    return float(brentq(loop_angle_error, low, high, xtol=0.01))


def generate_cylindrical_panorama(images, focal_length=None, feature_matcher=None,
                                  threshold=3.0, seed=0, blend='feather',
                                  close_loop=False, return_info=False):
    """Match original frames, align cylinder coordinates, sample originals once.

    close_loop is ONLY for an ordered, complete one-turn sequence whose first
    and last frames overlap. It matches that pair, distributes closure drift
    over all edges, and renders with period 2*pi*f (including the wrap seam).
    focal_length=None estimates f from full-turn closure (close_loop required).
    A focal guess is not camera calibration; inspect residuals and ghosting.
    """
    images = list(images)
    if len(images) < 2:
        raise ValueError('Choose at least two ordered, overlapping images')
    if any(im is None or im.shape != images[0].shape for im in images):
        raise ValueError('Images must be readable and share resolution/channels')
    if feature_matcher is None:
        from homework2 import feature_matching
        feature_matcher = feature_matching

    n = len(images)
    pair_indices = [(i, i - 1) for i in range(1, n)]
    if close_loop:
        pair_indices.append((0, n - 1))
    # Cache original matches: f estimation must not rerun feature extraction.
    matches = {(i, j): feature_matcher(images[i], images[j])
               for i, j in pair_indices}
    estimated_focal = focal_length is None
    if estimated_focal:
        if not close_loop:
            raise ValueError('Specify focal_length for a partial/open panorama')
        focal_length = estimate_cylindrical_focal_length(
            matches.values(), images[0].shape, threshold=threshold, seed=seed)
    cylindrical_points([], images[0].shape, focal_length)
    f = float(focal_length)
    diagnostics = []

    def align(source_index, target_index):
        points1, points2 = matches[source_index, target_index]
        src = cylindrical_points(points1, images[source_index].shape, f)
        dst = cylindrical_points(points2, images[target_index].shape, f)
        shift, inliers = ransac_translation(src, dst, threshold=threshold, seed=seed)
        count = int(inliers.sum())
        if count < 3:
            raise ValueError(f'Frames {source_index} -> {target_index}: '
                             f'only {count} translation inliers; check focal length '
                             'and the level-rotation assumption')
        residuals = np.linalg.norm(src + shift - dst, axis=1)
        diagnostics.append({
            'source_index': source_index, 'target_index': target_index,
            'matches': len(src), 'inliers': count,
            'inlier_ratio': count / len(src), 'shift': shift.tolist(),
            'median_inlier_error': float(np.median(residuals[inliers])),
        })
        return shift

    offsets = np.zeros((n, 2), np.float64)
    for i in range(1, n):
        # t_i maps frame i's local cylinder coordinates into frame i-1's.
        offsets[i] = offsets[i - 1] + align(i, i - 1)

    period = 2 * np.pi * f
    closure_error = None
    if close_loop:
        end_to_start = offsets[-1] + align(0, n - 1)
        winding = int(np.rint(end_to_start[0] / period))
        if abs(winding) != 1:
            raise ValueError('Loop does not span one full turn with this focal '
                             'length; use an open panorama or calibrate f')
        closure_error = end_to_start - np.array([winding * period, 0])
        # Uniform least-squares distribution over n edges, including closure.
        offsets -= np.arange(n)[:, None] / n * closure_error
    offsets -= offsets[n // 2].copy()

    bounds = np.array([_bounds(im.shape, f, offset)
                       for im, offset in zip(images, offsets)])
    top = int(np.floor(bounds[:, 1].min()))
    bottom = int(np.ceil(bounds[:, 3].max()))
    if close_loop:
        left, width = -period / 2, int(np.ceil(period))
    else:
        left = int(np.floor(bounds[:, 0].min()))
        width = int(np.ceil(bounds[:, 2].max())) - left + 1
    height = bottom - top + 1
    output_shape = (height, width) + images[0].shape[2:]
    accum = np.zeros(output_shape, np.float32)
    weight_sum = np.zeros((height, width), np.float32)
    global_u = left + np.arange(width, dtype=np.float32)[None, :]

    for image, offset in zip(images, offsets):
        source_weight = _source_weights(image.shape, blend)
        weight_channels = source_weight[..., None] if image.ndim == 3 else source_weight
        weighted_color = image.astype(np.float32) * weight_channels
        local_u = global_u - offset[0]
        if close_loop:
            local_u = (local_u + period / 2) % period - period / 2
        # Bounded working memory even for long panoramas.
        for row in range(0, height, 256):
            stop = min(row + 256, height)
            local_v = (top + np.arange(row, stop, dtype=np.float32)[:, None]
                       - offset[1])
            map_x, map_y = cylindrical_inverse_maps(local_u, local_v, image.shape, f)
            numerator = cv2.remap(weighted_color, map_x, map_y, cv2.INTER_LINEAR,
                                   borderMode=cv2.BORDER_CONSTANT, borderValue=0)
            weights = cv2.remap(source_weight, map_x, map_y, cv2.INTER_LINEAR,
                                borderMode=cv2.BORDER_CONSTANT, borderValue=0)
            # numerator already includes coverage/feather weight. Multiplying
            # by weights again would incorrectly darken the frame boundaries.
            accum[row:stop] += numerator
            weight_sum[row:stop] += weights

    denominator = weight_sum[..., None] if accum.ndim == 3 else weight_sum
    panorama = np.clip(accum / np.maximum(denominator, 1e-6), 0, 255)
    panorama = np.rint(panorama).astype(np.uint8)
    info = {
        'projection': 'cylindrical; original color frames sampled once',
        'focal_length_pixels': f, 'blend': blend, 'closed_360': close_loop,
        'focal_source': 'full-turn closure estimate' if estimated_focal else 'specified',
        'period_pixels': period, 'anchor_index': n // 2,
        'canvas_origin_uv': [float(left), float(top)],
        'canvas_width': width, 'canvas_height': height,
        'offsets': offsets.tolist(), 'pairs': diagnostics,
        'closure_error_before_correction':
            None if closure_error is None else closure_error.tolist(),
        'covered_fraction': float(np.mean(weight_sum > 1e-6)),
    }
    return (panorama, info) if return_info else panorama
